function normalizeLocale(value) {
  return /^ru(?:[-_]|$)/i.test(String(value || "")) ? "ru" : "en";
}

function translate(locale, key, parameters = {}) {
  const normalized = normalizeLocale(locale);
  const template = MESSAGES[normalized][key] ?? MESSAGES.ru[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_match, name) => (
    Object.prototype.hasOwnProperty.call(parameters, name)
      ? String(parameters[name])
      : `{${name}}`
  ));
}

